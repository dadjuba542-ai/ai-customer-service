def seed_bank(conn):
    timestamp = datetime.now(timezone.utc).isoformat()
    for category_index, (category, text) in enumerate(RAW.items()):
        rows = text.strip().splitlines()
        assert len(rows) == 25, (category, len(rows))
        for local_index, row in enumerate(rows):
            title, best, b, c, d, explanation, method = row.split('|')
            index = local_index * 4 + category_index
            options = [best, b, c, d]
            shift = index % 4
            options = options[shift:] + options[:shift]
            conn.execute('''INSERT OR IGNORE INTO practice_quiz_questions
                (id,batch_no,category,title,options,answer_index,explanation,method,sources,enabled,updated_at)
                VALUES(?,?,?,?,?,?,?,?,?,1,?)''',
                (index + 1, index // 10 + 1, category, title, json.dumps(options, ensure_ascii=False),
                 (-shift) % 4, explanation, method,
                 json.dumps(FACT_SOURCES.get((category, local_index), [])), timestamp))
